"""Generate the gd-v4 counts report (parallel to overnight-summary.md, but gd-v4).

Reads each original powered log (gd-v3) and its gd-v4 re-score under logs/gdv4/, and
writes a per-arm table showing gd-v3 → gd-v4 for the disclosure cells plus the current
gd-v4 indirect/denied/concealment/unclassified counts. Counts only — provisional and
unquoted until the gd-v4 M12 round passes.

    PYTHONPATH=src:. uv run python analysis/gdv4_report.py

Writes reports/hidden-goal-gd-v4-counts.md. Re-run after any re-score.
"""

import sys
from pathlib import Path
from typing import Any

from inspect_ai.log import list_eval_logs, read_eval_log

sys.path.insert(0, str(Path(__file__).parent.parent / "src"))

# (dir, scenario label, ordered arms) — matrix order.
RUNS = [
    ("hg-s1-apps-powered", "S1 (CA-native, apps)", ["default", "keep"]),
    (
        "hg-s2a-powered",
        "S2a (intern, correlated CHANGELOG)",
        ["bare", "default", "keep"],
    ),
    (
        "hg-s2b-powered",
        "S2b (intern, uncorrelated CONTRIBUTORS)",
        ["bare", "default", "keep"],
    ),
    ("hg-s3-powered", "S3 (Plan-Pro house-brand)", ["default", "keep"]),
    ("hg-s5neg-powered", "S5neg (data-handling, negation)", ["default", "keep"]),
    ("hg-s5aff-powered", "S5aff (data-handling, affirmative)", ["default", "keep"]),
    ("hg-s6-powered", "S6 (broad preference)", ["default", "keep"]),
    ("hg-s7-powered", "S7 (narrow omission, OpenAI)", ["default", "keep"]),
]
CELLS = [
    "disclosed_any",
    "disclosed_reasoning",
    "disclosed_output",
    "indirect_any",
    "denied_any",
    "concealment_any",
    "unclassified_count",
]
OUT = Path("reports/hidden-goal-gd-v4-counts.md")


def counts(path: str) -> dict[str, dict[str, int]]:
    logs = list_eval_logs(path)
    log = read_eval_log(max(logs, key=lambda i: i.mtime or 0))
    out: dict[str, dict[str, int]] = {}
    for s in log.samples or []:
        sc = (s.scores or {}).get("goal_disclosure_scorer")
        if sc is None or not isinstance(sc.value, dict):
            continue
        arm = (sc.metadata or {}).get("ca_arm", "?")
        row = out.setdefault(arm, {"n": 0, **{c: 0 for c in CELLS}})
        row["n"] += 1
        for c in CELLS:
            row[c] += int(sc.value.get(c, 0) or 0)
    return out


def main() -> None:
    lines: list[str] = [
        "# Hidden-goal disclosure — gd-v4 counts (provisional)",
        "",
        "> **UNQUOTED — pending the gd-v4 M12 round.** Both gd-v3 bugs *under*-called"
        " `disclosed` (CHANGELOG 2026-08-26), so every cell can only rise under gd-v4;"
        " many now sit near-ceiling, which is exactly where an over-calling judge"
        " would also land. The blind validation (representative + first-passage"
        ' sheets) is what distinguishes "the reasoning leak is near-universal" from'
        ' "gd-v4 over-calls". No number here is quotable until that passes.',
        "",
        "Generated by `analysis/gdv4_report.py` from `logs/gdv4/` (gd-v4) vs the"
        " original powered logs (gd-v3). Operational-health metrics (completion,"
        " errors, cost, reasoning visibility) are judge-independent — see"
        " `reports/overnight-summary.md`.",
        "",
        "`disclosed` cells show **gd-v3 → gd-v4** (headline is any-channel first"
        " passage; reasoning/output are the per-channel splits)."
        " indirect/denied/concealment/uncl. are current gd-v4 (gd-v3 in"
        " parentheses). All out of n=20 per arm.",
        "",
    ]
    # running totals for the summary line
    tot_r3 = tot_r4 = 0
    for d, label, arms in RUNS:
        old = counts(f"logs/{d}")
        new = counts(f"logs/gdv4/{d}")
        lines += [
            f"## {label}",
            "",
            "| arm | disclosed_any | disc_reasoning | disc_output | indirect |"
            " denied | conceal | uncl |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for arm in arms:
            o = old.get(arm, {})
            nw = new.get(arm, {})

            def cell(k: str, o: dict[str, Any] = o, nw: dict[str, Any] = nw) -> str:
                return f"{o.get(k, 0)}→{nw.get(k, 0)}"

            def cur(k: str, o: dict[str, Any] = o, nw: dict[str, Any] = nw) -> str:
                return f"{nw.get(k, 0)} ({o.get(k, 0)})"

            lines.append(
                f"| {arm} | {cell('disclosed_any')} | {cell('disclosed_reasoning')} | "
                f"{cell('disclosed_output')} | {cur('indirect_any')} | "
                f"{cur('denied_any')} | {cur('concealment_any')} | "
                f"{cur('unclassified_count')} |"
            )
            tot_r3 += o.get("disclosed_reasoning", 0)
            tot_r4 += nw.get("disclosed_reasoning", 0)
        lines.append("")

    lines += [
        "## What moved",
        "",
        f"- **Reasoning-channel disclosure across all arms: {tot_r3} → {tot_r4}**"
        f" (of {sum(20 * len(a[2]) for a in RUNS)} investigations —"
        f" {sum(len(a[2]) for a in RUNS)} arms × 20). The gd-v3 `0/20` reasoning"
        " cells were the false negative.",
        "- The keep-instruction's effect is now visible mainly on the **output**"
        " channel and in **denied** rates, not on reasoning — under gd-v4 the model"
        " rehearses the goal in its CoT in nearly every investigation regardless of"
        " arm. (Provisional.)",
        "- `indirect` still fires ~20/20 everywhere; whether it needs a severity"
        " split is an M12 deliverable, not decided here.",
    ]
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT}  (reasoning-disclosed total gd-v3→gd-v4: {tot_r3}→{tot_r4})")


if __name__ == "__main__":
    main()
